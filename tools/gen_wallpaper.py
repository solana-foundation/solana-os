#!/usr/bin/env python3
# Render the themes' wallpapers (main/core/ui_theme.c) as LVGL 9 RGB565 image
# descriptors: main/assets/img_wall_<name>.c, 320x240, opaque.
#
# A wallpaper is a ground colour with a few soft colour blobs, the way the
# design draws it with blurred ellipses. The panel shows 16-bit colour, so
# the smooth falloff is ordered-dithered here or it would band.
#
# usage: python3 tools/gen_wallpaper.py [--png dir]   (--png also writes previews; needs Pillow)
import math
import os
import sys

W, H = 320, 240

# name: (ground, [(cx, cy, rx, ry, colour, opacity)]) in screen pixels.
WALLS = {
    "pearl": (0xF4F0EC, [
        (60, 30, 150, 125, 0xA9CBF5, 0.85),
        (275, 95, 145, 120, 0xF5B5D0, 0.85),
        (140, 240, 150, 110, 0xB4E8D6, 0.90),
        (270, 235, 125, 105, 0xCDBEF5, 0.85),
    ]),
    "black_pearl": (0x08070C, [
        (45, 15, 160, 135, 0x1E8F86, 0.55),
        (290, 95, 155, 135, 0x7A3FA8, 0.55),
        (170, 270, 155, 115, 0xB8705E, 0.40),
    ]),
    "aurora": (0x060913, [
        (26, 29, 170, 140, 0x2F7BFF, 0.60),
        (307, 82, 190, 150, 0xE0457B, 0.52),
        (147, 259, 200, 130, 0xFFA24A, 0.42),
    ]),
}

BAYER = [[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]


def rgb(c):
    return ((c >> 16) & 255, (c >> 8) & 255, c & 255)


def render(ground, blobs):
    out = []
    g = rgb(ground)
    for y in range(H):
        for x in range(W):
            r, gg, b = g
            for cx, cy, rx, ry, col, op in blobs:
                d2 = ((x - cx) / rx) ** 2 + ((y - cy) / ry) ** 2
                a = op * math.exp(-2.6 * d2)
                cr, cg, cb = rgb(col)
                r += (cr - r) * a
                gg += (cg - gg) * a
                b += (cb - b) * a
            out.append((r, gg, b))
    return out


def quantise(px):
    data = bytearray()
    shown = []
    for i, (r, g, b) in enumerate(px):
        t = (BAYER[(i // W) & 3][i & 3] + 0.5) / 16 - 0.5
        r5 = min(31, max(0, int(r / 255 * 31 + 0.5 + t)))
        g6 = min(63, max(0, int(g / 255 * 63 + 0.5 + t)))
        b5 = min(31, max(0, int(b / 255 * 31 + 0.5 + t)))
        v = (r5 << 11) | (g6 << 5) | b5
        data += bytes((v & 0xFF, v >> 8))
        shown.append((r5 * 255 // 31, g6 * 255 // 63, b5 * 255 // 31))
    return data, shown


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    assets = os.path.join(here, "..", "main", "assets")
    png = sys.argv[2] if len(sys.argv) > 2 and sys.argv[1] == "--png" else None
    for name, (ground, blobs) in WALLS.items():
        data, shown = quantise(render(ground, blobs))
        sym = f"img_wall_{name}"
        path = os.path.join(assets, sym + ".c")
        with open(path, "w") as f:
            f.write("// Generated by tools/gen_wallpaper.py. Do not edit.\n")
            f.write('#include "lvgl.h"\n\n')
            f.write(f"static const uint8_t {sym}_map[] = {{\n")
            for i in range(0, len(data), 24):
                f.write("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",\n")
            f.write("};\n\n")
            f.write(f"const lv_image_dsc_t {sym} = {{\n"
                    f"    .header = {{ .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565,\n"
                    f"                .w = {W}, .h = {H}, .stride = {W * 2} }},\n"
                    f"    .data_size = sizeof({sym}_map),\n"
                    f"    .data = {sym}_map,\n}};\n")
        print(f"{path}: {W}x{H}, {len(data)} bytes")
        if png:
            from PIL import Image
            img = Image.new("RGB", (W, H))
            img.putdata(shown)
            img.save(os.path.join(png, name + ".png"))


if __name__ == "__main__":
    main()
