#!/usr/bin/env python3
# Convert a PNG to an opaque LVGL 9 RGB565 image descriptor (C source), with
# a 4x4 ordered dither so soft gradients don't band on the 16-bit panel.
# usage: python3 tools/img2lvgl565.py <in.png> <symbol_name> <out.c>
import sys
from PIL import Image

BAYER = [[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]
src, name, out = sys.argv[1:4]
img = Image.open(src).convert("RGB")
w, h = img.size
px = img.load()
data = bytearray()
for y in range(h):
    for x in range(w):
        r, g, b = px[x, y]
        d = (BAYER[y & 3][x & 3] + 0.5) / 16 - 0.5
        r5 = max(0, min(31, round(r / 255 * 31 + d)))
        g6 = max(0, min(63, round(g / 255 * 63 + d)))
        b5 = max(0, min(31, round(b / 255 * 31 + d)))
        v = (r5 << 11) | (g6 << 5) | b5
        data += bytes((v & 0xFF, v >> 8))

with open(out, "w") as f:
    f.write(f"// Generated by tools/img2lvgl565.py from {src.split('/')[-1]}. Do not edit.\n")
    f.write('#include "lvgl.h"\n\n')
    f.write(f"static const uint8_t {name}_map[] = {{\n")
    for i in range(0, len(data), 24):
        f.write("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",\n")
    f.write("};\n\n")
    f.write(f"const lv_image_dsc_t {name} = {{\n"
            f"    .header = {{ .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565,\n"
            f"                .w = {w}, .h = {h}, .stride = {w * 2} }},\n"
            f"    .data_size = sizeof({name}_map),\n"
            f"    .data = {name}_map,\n}};\n")
print(f"{out}: {w}x{h}")
